std::string bukaSandi() {
    const size_t n = sizeof(SANDI);
    const size_t k = sizeof(KUNCI);
    std::string keluar;
    keluar.resize(n);
    for (size_t i = 0; i < n; i++) {
        keluar[i] = static_cast<char>(SANDI[i] ^ KUNCI[i % k]);
    }
    return keluar;
}

void seedDariFragmen(uint8_t seed[32], bool& konsisten) {
    kepem::Fragmen utama{{kepem_frag_u0(), kepem_frag_u1(),
                          kepem_frag_u2(), kepem_frag_u3()}};
    kepem::Fragmen cadangan{{kepem_frag_c0(), kepem_frag_c1(),
                             kepem_frag_c2(), kepem_frag_c3()}};
    kepem::rakitSeed(utama, cadangan, seed, konsisten);
}

