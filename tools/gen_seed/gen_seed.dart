import 'dart:io';

import 'package:crypto/crypto.dart';

void main() {
  void cetak(String s) => stdout.writeln(s);

  const kunci = <int>[0x5A, 0xA5, 0x3C, 0xC3, 0x7E, 0x19, 0xE7];
  const sandi = <int>[
    0x98, 0x0c, 0x1c, 0xf1, 0x4e, 0x2b, 0xd3, 0xb8, 0x25, 0xaf, 0xf1, 0x4e,
    0x2b, 0xd1, 0x7a, 0xf7, 0x7d, 0x8a, 0x36, 0x58, 0xa9, 0x7a, 0xeb, 0x69,
    0x84, 0x2c, 0x56, 0xaf, 0x15, 0x85, 0xde, 0x43, 0xea, 0x39, 0xa5, 0x1b,
    0xee, 0x69, 0x87, 0x3f, 0x49, 0xa6, 0x7a, 0xe8, 0x73, 0x81, 0x37, 0x55,
    0xa2, 0x7a, 0xd9, 0x1c, 0x87, 0x17, 0x6a, 0x83, 0x2f, 0xce, 0x5f, 0xa2,
    0x0e, 0x70, 0x8b, 0x7a, 0xf5, 0x4e, 0xac, 0x08, 0x70, 0x89, 0x29, 0xcc,
    0x1c, 0x8e, 0x1f, 0x75, 0x92, 0x31, 0xd0, 0x1c, 0x96, 0x0a, 0x78, 0x95,
    0x3b, 0x85, 0x40, 0xe3, 0x2d, 0x7c, 0x8b, 0x2f, 0xd7, 0x49, 0xab, 0x5e,
    0x71, 0x86, 0x31, 0x85, 0x58, 0xaa, 0x12, 0x70, 0x89, 0x3e, 0xd0, 0x52,
    0xa4, 0x17, 0x39, 0x92, 0x34, 0xc1, 0x5d, 0xad, 0x19, 0x34, 0x92, 0x34,
    0xc1, 0x5d, 0xad, 0x19, 0x37,
  ];

  final rahasia = <int>[
    for (var i = 0; i < sandi.length; i++) sandi[i] ^ kunci[i % kunci.length],
  ];
  final seed = sha256.convert(rahasia).bytes;
  String heks(Iterable<int> b) =>
      b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

  cetak('seed=${heks(seed)}');
  for (var i = 0; i < 4; i++) {
    final h = heks(seed.sublist(i * 8, i * 8 + 8));
    cetak('F$i=0x$h');
    final w = [
      h.substring(12, 16),
      h.substring(8, 12),
      h.substring(4, 8),
      h.substring(0, 4),
    ];
    cetak('  arm64  movz #0x${w[0]} / movk lsl16 #0x${w[1]} / lsl32 #0x${w[2]} / lsl48 #0x${w[3]}');
    cetak('  x86_64 movabs \$0x$h');
    final loL = h.substring(12, 16);
    final loH = h.substring(8, 12);
    final hiL = h.substring(4, 8);
    final hiH = h.substring(0, 4);
    cetak('  armv7  r0: movw 0x$loL movt 0x$loH | r1: movw 0x$hiL movt 0x$hiH');
  }
}
